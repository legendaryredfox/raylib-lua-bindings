#!/usr/bin/env python3
"""Generate src/lua_raylib_math.c from raylib/src/raymath.h.

Every `RMAPI` function becomes a module function with the same name
(raylib.Vector2Add, raylib.Clamp, raylib.MatrixMultiply, ...). Vectors and
quaternions are {x,y,z[,w]} tables, matrices are {m0..m15} tables. Functions
that use out-pointers or float arrays are handwritten below.

Usage (from the repo root):  python3 tools/gen_raymath.py
"""
import re
import sys
from pathlib import Path

HEADER = Path("raylib/src/raymath.h")
OUT = Path("src/lua_raylib_math.c")

text = HEADER.read_text()
sigs = re.findall(r"^RMAPI\s+(.+?)\s*\{", text, flags=re.M)

# name -> custom C body (functions with out-pointers or array results)
CUSTOM = {
    "Vector3OrthoNormalize": """    Vector3 v1 = get_vector3_from_table(L, 1);
    Vector3 v2 = get_vector3_from_table(L, 2);
    Vector3OrthoNormalize(&v1, &v2);
    push_vector3_to_table(L, v1);
    push_vector3_to_table(L, v2);
    return 2;""",
    "Vector3ToFloatV": """    float3 f = Vector3ToFloatV(get_vector3_from_table(L, 1));
    lua_createtable(L, 3, 0);
    for (int i = 0; i < 3; i++) { lua_pushnumber(L, f.v[i]); lua_rawseti(L, -2, i + 1); }
    return 1;""",
    "MatrixToFloatV": """    float16 f = MatrixToFloatV(get_matrix_from_table(L, 1));
    lua_createtable(L, 16, 0);
    for (int i = 0; i < 16; i++) { lua_pushnumber(L, f.v[i]); lua_rawseti(L, -2, i + 1); }
    return 1;""",
    "QuaternionToAxisAngle": """    Vector3 axis;
    float angle;
    QuaternionToAxisAngle(get_vector4_from_table(L, 1), &axis, &angle);
    push_vector3_to_table(L, axis);
    lua_pushnumber(L, angle);
    return 2;""",
    "MatrixDecompose": """    Vector3 translation, scale;
    Quaternion rotation;
    MatrixDecompose(get_matrix_from_table(L, 1), &translation, &rotation, &scale);
    push_vector3_to_table(L, translation);
    push_vector4_to_table(L, rotation);
    push_vector3_to_table(L, scale);
    return 3;""",
}

GETTERS = {
    "float":      lambda i: f"(float)luaL_checknumber(L, {i})",
    "double":     lambda i: f"luaL_checknumber(L, {i})",
    "int":        lambda i: f"(int)luaL_checkinteger(L, {i})",
    "Vector2":    lambda i: f"get_vector2_from_table(L, {i})",
    "Vector3":    lambda i: f"get_vector3_from_table(L, {i})",
    "Vector4":    lambda i: f"get_vector4_from_table(L, {i})",
    "Quaternion": lambda i: f"get_vector4_from_table(L, {i})",
    "Matrix":     lambda i: f"get_matrix_from_table(L, {i})",
}
PUSHERS = {
    "float":      "lua_pushnumber(L, {e});",
    "Vector2":    "push_vector2_to_table(L, {e});",
    "Vector3":    "push_vector3_to_table(L, {e});",
    "Vector4":    "push_vector4_to_table(L, {e});",
    "Quaternion": "push_vector4_to_table(L, {e});",
    "Matrix":     "push_matrix_to_table(L, {e});",
    "int":        "lua_pushinteger(L, {e});",
}

funcs = []
body = []
for sig in sigs:
    m = re.match(r"(\w+)\s+(\w+)\((.*)\)\s*$", sig)
    if not m:
        sys.exit(f"cannot parse: {sig}")
    ret, name, params = m.groups()
    funcs.append(name)
    if name in CUSTOM:
        body.append(f"static int rm_{name}(lua_State *L) {{\n{CUSTOM[name]}\n}}\n")
        continue
    args = []
    decls = []
    plist = [] if params.strip() in ("", "void") else [p.strip() for p in params.split(",")]
    for i, p in enumerate(plist, start=1):
        p = re.sub(r"\bconst\b", "", p).strip()
        t, n = p.rsplit(None, 1)
        if t not in GETTERS:
            sys.exit(f"unsupported param type {t} in {sig}")
        decls.append(f"    {t} {n} = {GETTERS[t](i)};")
        args.append(n)
    call = f"{name}({', '.join(args)})"
    if ret == "int" and name.endswith("Equals"):
        push = f"lua_pushboolean(L, {call});"      # raymath returns 0/1
    elif ret in PUSHERS:
        push = PUSHERS[ret].format(e=call)
    else:
        sys.exit(f"unsupported return type {ret} in {sig}")
    lines = decls + [f"    {push}", "    return 1;"]
    body.append(f"static int rm_{name}(lua_State *L) {{\n" + "\n".join(lines) + "\n}\n")

reg = "\n".join(f'    {{"{n}", rm_{n}}},' for n in funcs)
OUT.write_text(f"""// lua_raylib_math.c
//
// GENERATED by tools/gen_raymath.py from raylib/src/raymath.h -- do not edit.
// Exposes the raymath API (vectors, quaternions, matrices, scalar helpers) on the
// module table: Vector2/3/4 and Quaternion are {{x,y,z[,w]}} tables, Matrix is {{m0..m15}}.

#include "raylib.h"
#include "raymath.h"
#include <lua.h>
#include <lauxlib.h>
#include "raylib_wrappers.h"

{chr(10).join(body)}
static const luaL_Reg math_functions[] = {{
{reg}
    {{NULL, NULL}}
}};

// Adds the raymath functions onto the module table currently on top of the stack.
void register_raylib_math(lua_State *L) {{
    luaL_setfuncs(L, math_functions, 0);
}}
""")
print(f"{len(funcs)} raymath functions -> {OUT}", file=sys.stderr)
