#!/usr/bin/env python3
"""Generate src/lua_raylib_constants.c from raylib/src/raylib.h.

Every enum member (and every `#define NAME OTHER_ENUM_MEMBER` alias such as
MOUSE_LEFT_BUTTON) is registered on the module table as an integer, so scripts
can write raylib.KEY_A instead of 65. Values are emitted as C references and
resolved by the compiler, so the numbers can never drift from the header.

Usage (from the repo root):  python3 tools/gen_constants.py
"""
import re
import sys
from pathlib import Path

HEADER = Path("raylib/src/raylib.h")
OUT = Path("src/lua_raylib_constants.c")

# Enum members that are not constants worth exposing.
SKIP = {"false", "true"}

text = HEADER.read_text()
no_comments = re.sub(r"//[^\n]*", "", re.sub(r"/\*.*?\*/", "", text, flags=re.S))

groups = []   # (enum name, [member names])
for m in re.finditer(r"(?:typedef\s+)?enum\s*(\w*)\s*\{(.*?)\}\s*(\w*)\s*;", no_comments, flags=re.S):
    name = m.group(3) or m.group(1) or "(anonymous)"
    members = []
    for item in m.group(2).split(","):
        item = item.strip()
        if not item:
            continue
        ident = re.match(r"[A-Za-z_]\w*", item)
        if ident and ident.group(0) not in SKIP:
            members.append(ident.group(0))
    if members:
        groups.append((name, members))

known = {mem for _, members in groups for mem in members}

# #define ALIAS EXISTING_MEMBER  (e.g. MOUSE_LEFT_BUTTON -> MOUSE_BUTTON_LEFT)
aliases = []
for m in re.finditer(r"^\s*#define\s+([A-Z][A-Z0-9_]*)\s+([A-Z][A-Z0-9_]*)\s*$", no_comments, flags=re.M):
    if m.group(2) in known and m.group(1) not in known:
        aliases.append((m.group(1), m.group(2)))

seen = set()
lines = []
for name, members in groups:
    lines.append(f"    /* {name} */")
    for mem in members:
        if mem in seen:
            continue
        seen.add(mem)
        lines.append(f'    {{"{mem}", (lua_Integer){mem}}},')
if aliases:
    lines.append("    /* #define aliases */")
    for alias, target in aliases:
        if alias in seen:
            continue
        seen.add(alias)
        lines.append(f'    {{"{alias}", (lua_Integer){alias}}},')

OUT.write_text(f"""// lua_raylib_constants.c
//
// GENERATED by tools/gen_constants.py from raylib/src/raylib.h -- do not edit.
// Registers every raylib enum member (KEY_*, MOUSE_BUTTON_*, FLAG_*, PIXELFORMAT_*,
// ...) and the PI / DEG2RAD / RAD2DEG / RAYLIB_VERSION values on the module table.

#include "raylib.h"
#include <lua.h>
#include <lauxlib.h>

typedef struct {{
    const char *name;
    lua_Integer value;
}} IntConstant;

static const IntConstant int_constants[] = {{
{chr(10).join(lines)}
}};

// Adds the constants onto the module table currently on top of the stack.
void register_raylib_constants(lua_State *L) {{
    for (size_t i = 0; i < sizeof(int_constants) / sizeof(int_constants[0]); i++) {{
        lua_pushinteger(L, int_constants[i].value);
        lua_setfield(L, -2, int_constants[i].name);
    }}
    // raylib defines these as floats; use the double values so Lua math stays precise
    lua_pushnumber(L, 3.14159265358979323846);                   lua_setfield(L, -2, "PI");
    lua_pushnumber(L, 3.14159265358979323846 / 180.0);           lua_setfield(L, -2, "DEG2RAD");
    lua_pushnumber(L, 180.0 / 3.14159265358979323846);           lua_setfield(L, -2, "RAD2DEG");
    lua_pushstring(L, RAYLIB_VERSION);        lua_setfield(L, -2, "RAYLIB_VERSION");
    lua_pushinteger(L, RAYLIB_VERSION_MAJOR); lua_setfield(L, -2, "RAYLIB_VERSION_MAJOR");
    lua_pushinteger(L, RAYLIB_VERSION_MINOR); lua_setfield(L, -2, "RAYLIB_VERSION_MINOR");
    lua_pushinteger(L, RAYLIB_VERSION_PATCH); lua_setfield(L, -2, "RAYLIB_VERSION_PATCH");
}}
""")
print(f"{len(seen)} constants in {len(groups)} enums ({len(aliases)} aliases) -> {OUT}", file=sys.stderr)
